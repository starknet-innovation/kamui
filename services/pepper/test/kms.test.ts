// The KMS-backed key holder, against a fake MAC client that computes HMAC-SHA-256 locally.
// AWS itself is not called: what is tested is that this service asks for the right MACs, turns
// them into the same peppers as the in-memory deriver, and refuses a key it should not use.
import { describe, expect, test } from 'bun:test';
import { createHmac, randomBytes } from 'node:crypto';
import { keySource, kmsSettings, loadKmsDeriver } from '../src/config';
import { encodeInput, inMemoryDeriver, keyCheckValue } from '../src/derive';
import { assertPepperKey, macDeriver, macKeyCheckValue, type KmsKeyInfo, type MacClient } from '../src/kms';

const GOOGLE = 'https://accounts.google.com';
const ARN = 'arn:aws:kms:eu-west-1:123456789012:key/1234abcd-12ab-34cd-56ef-1234567890ab';

function fakeKms(key: Uint8Array, info: Partial<KmsKeyInfo> = {}) {
  const messages: Uint8Array[] = [];
  const client: MacClient = {
    async generateMac(message) {
      messages.push(message);
      return Uint8Array.from(createHmac('sha256', key).update(message).digest());
    },
  };
  const key_info: KmsKeyInfo = {
    arn: ARN,
    keySpec: 'HMAC_256',
    keyUsage: 'GENERATE_VERIFY_MAC',
    origin: 'AWS_KMS',
    enabled: true,
    multiRegion: true,
    pendingDeletion: false,
    ...info,
  };
  return { client, describe: async () => key_info, messages };
}

const newKey = () => Uint8Array.from(randomBytes(32));

describe('KMS deriver', () => {
  test('gives the same pepper as the in-memory deriver for the same key', async () => {
    const key = newKey();
    const kms = fakeKms(key);
    const viaKms = macDeriver(kms.client, 1);
    const inMemory = inMemoryDeriver(key, 1);
    for (const [iss, sub] of [[GOOGLE, '1'], [GOOGLE, '123456789012345678901'], ['https://appleid.apple.com', 'abc.def']] as const) {
      expect(await viaKms.derive(iss, sub)).toBe(await inMemory.derive(iss, sub));
    }
  });

  test('sends KMS exactly the derivation message, nothing else', async () => {
    const kms = fakeKms(newKey());
    await macDeriver(kms.client, 1).derive(GOOGLE, 'sub-1');
    expect(kms.messages).toHaveLength(1);
    expect(Buffer.from(kms.messages[0]!).equals(Buffer.from(encodeInput(GOOGLE, 'sub-1')))).toBe(true);
  });

  test('the key check value matches the in-memory one', async () => {
    const key = newKey();
    expect(await macKeyCheckValue(fakeKms(key).client)).toBe(keyCheckValue(key));
  });

  test('refuses empty input and a MAC of the wrong length', async () => {
    const kms = fakeKms(newKey());
    await expect(macDeriver(kms.client, 1).derive('', 'x')).rejects.toThrow('EMPTY_INPUT');
    const short: MacClient = { generateMac: async () => new Uint8Array(16) };
    await expect(macDeriver(short, 1).derive(GOOGLE, 'x')).rejects.toThrow('BAD_MAC_LENGTH');
    await expect(macKeyCheckValue(short)).rejects.toThrow('BAD_MAC_LENGTH');
  });

  test('a KMS failure surfaces as an error, not as a pepper', async () => {
    const failing: MacClient = { generateMac: async () => { throw new Error('AccessDeniedException'); } };
    await expect(macDeriver(failing, 1).derive(GOOGLE, 'x')).rejects.toThrow();
  });
});

describe('KMS key checks', () => {
  const good: KmsKeyInfo = { arn: ARN, keySpec: 'HMAC_256', keyUsage: 'GENERATE_VERIFY_MAC', origin: 'AWS_KMS', enabled: true, pendingDeletion: false };

  test('accepts the key the design calls for', () => {
    expect(() => assertPepperKey(good)).not.toThrow();
  });

  test('refuses any other kind of key', () => {
    expect(() => assertPepperKey({ ...good, keySpec: 'HMAC_512' })).toThrow(/HMAC_256/);
    expect(() => assertPepperKey({ ...good, keySpec: 'SYMMETRIC_DEFAULT' })).toThrow(/HMAC_256/);
    expect(() => assertPepperKey({ ...good, keyUsage: 'ENCRYPT_DECRYPT' })).toThrow(/usage/);
    expect(() => assertPepperKey({ ...good, origin: 'EXTERNAL' })).toThrow(/generated by AWS KMS/);
    expect(() => assertPepperKey({ ...good, enabled: false })).toThrow(/disabled/);
    expect(() => assertPepperKey({ ...good, pendingDeletion: true })).toThrow(/deletion/);
  });
});

describe('KMS startup', () => {
  test('starts only with a matching key check value', async () => {
    const key = newKey();
    const check = keyCheckValue(key);
    const { deriver, key: info } = await loadKmsDeriver({ PEPPER_KEY_CHECK: check, PEPPER_KEY_VERSION: '2' }, fakeKms(key));
    expect(deriver.version).toBe(2);
    expect(info.multiRegion).toBe(true);
    expect(await deriver.derive(GOOGLE, 'x')).toBe(await inMemoryDeriver(key, 2).derive(GOOGLE, 'x'));
  });

  test('refuses to start without a key check value', async () => {
    await expect(loadKmsDeriver({}, fakeKms(newKey()))).rejects.toThrow(/PEPPER_KEY_CHECK is required/);
    await expect(loadKmsDeriver({ PEPPER_KEY_CHECK: 'abcd' }, fakeKms(newKey()))).rejects.toThrow(/required/);
  });

  test('refuses another key, and never prints the check value it computed', async () => {
    const intended = newKey();
    const other = newKey();
    const error = await loadKmsDeriver({ PEPPER_KEY_CHECK: keyCheckValue(intended) }, fakeKms(other)).then(() => null, (e: Error) => e);
    expect(error?.message).toMatch(/does not match/);
    expect(error?.message).not.toContain(keyCheckValue(other));
  });

  test('refuses a key scheduled for deletion before asking it for anything', async () => {
    const key = newKey();
    const kms = fakeKms(key, { pendingDeletion: true });
    await expect(loadKmsDeriver({ PEPPER_KEY_CHECK: keyCheckValue(key) }, kms)).rejects.toThrow(/deletion/);
    expect(kms.messages).toHaveLength(0);
  });
});

describe('KMS settings', () => {
  test('the key source defaults to env and accepts kms', () => {
    expect(keySource({})).toBe('env');
    expect(keySource({ PEPPER_KEY_SOURCE: 'kms' })).toBe('kms');
    expect(() => keySource({ PEPPER_KEY_SOURCE: 'file' })).toThrow();
  });

  test('the key must be named by ARN, and the Region defaults to the ARN one', () => {
    expect(kmsSettings({ KMS_KEY_ID: ARN })).toEqual({ keyId: ARN, region: 'eu-west-1' });
    expect(kmsSettings({ KMS_KEY_ID: ARN, AWS_REGION: 'eu-central-1' }).region).toBe('eu-central-1');
    expect(() => kmsSettings({ KMS_KEY_ID: 'alias/pepper' })).toThrow(/ARN/);
    expect(() => kmsSettings({ KMS_KEY_ID: '1234abcd-12ab-34cd-56ef-1234567890ab' })).toThrow(/ARN/);
    expect(() => kmsSettings({})).toThrow(/ARN/);
  });
});
