// Registry display data is private. No account, origin or session is logged here.
import type { SQL } from 'bun';
import { MAX_SESSIONS_PER_ACCOUNT, type ListedSession, type RegistryStorage, type StoredSession } from './store';

export const REGISTRY_SCHEMA_SQL = `
CREATE TABLE IF NOT EXISTS registry_sessions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  account TEXT NOT NULL,
  public_key TEXT NOT NULL,
  valid_until BIGINT NOT NULL,
  created_at BIGINT NOT NULL,
  session TEXT NOT NULL,
  UNIQUE (account, public_key)
);
CREATE INDEX IF NOT EXISTS registry_sessions_valid_until ON registry_sessions (valid_until);
CREATE TABLE IF NOT EXISTS registry_used_messages (
  message TEXT PRIMARY KEY,
  expires BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS registry_used_messages_expires ON registry_used_messages (expires);
`;

/** PostgreSQL returns BIGINT as a string or bigint depending on driver options. */
function safeInteger(value: unknown): number {
  const result = Number(value);
  if (!Number.isSafeInteger(result)) throw new Error('REGISTRY_INTEGER_OUT_OF_RANGE');
  return result;
}

/** The caller owns the SQL connection/pool and initializes the shared schema. */
export class PostgresRegistryStore implements RegistryStorage {
  readonly journalMode = 'postgresql';
  constructor(private readonly sql: SQL, readonly maxPerAccount = MAX_SESSIONS_PER_ACCOUNT) {
    if (!Number.isSafeInteger(maxPerAccount) || maxPerAccount < 1) throw new Error('REGISTRY_LIMIT_INVALID');
  }

  async useOnce(message: string, expires: number, now: number): Promise<boolean> {
    await this.sql`DELETE FROM registry_used_messages WHERE expires < ${now}`;
    const rows = await this.sql`INSERT INTO registry_used_messages (message, expires) VALUES (${message}, ${expires}) ON CONFLICT (message) DO NOTHING RETURNING message`;
    return rows.length === 1;
  }

  async dropExpired(now: number): Promise<number> {
    const rows = await this.sql`DELETE FROM registry_sessions WHERE valid_until <= ${now} RETURNING id`;
    return rows.length;
  }

  async put(account: string, session: StoredSession, now: number): Promise<boolean> {
    return this.sql.begin(async tx => {
      // Lock even an account with no rows, so concurrent first inserts share the same limit.
      // Hash collisions only serialize unrelated accounts; they cannot bypass the limit.
      await tx`SELECT pg_advisory_xact_lock(hashtextextended(${'kamui.registry:' + account}, 0))`;
      await tx`DELETE FROM registry_sessions WHERE account = ${account} AND (valid_until <= ${now} OR public_key = ${session.publicKey})`;
      const [row] = await tx`SELECT COUNT(*) AS n FROM registry_sessions WHERE account = ${account}`;
      if (safeInteger(row.n) >= this.maxPerAccount) return false;
      await tx`INSERT INTO registry_sessions (account, public_key, valid_until, created_at, session)
        VALUES (${account}, ${session.publicKey}, ${session.validUntil}, ${now}, ${JSON.stringify(session)})`;
      return true;
    });
  }

  async list(account: string, now: number): Promise<ListedSession[]> {
    await this.sql`DELETE FROM registry_sessions WHERE account = ${account} AND valid_until <= ${now}`;
    const rows = await this.sql`SELECT session, created_at FROM registry_sessions WHERE account = ${account}
      AND valid_until > ${now} ORDER BY created_at DESC, id DESC LIMIT ${this.maxPerAccount}`;
    return rows.map((row: { session: string; created_at: string | bigint | number }) => ({ ...(JSON.parse(row.session) as StoredSession), createdAt: safeInteger(row.created_at) }));
  }

  async remove(account: string, publicKey: string): Promise<boolean> {
    const rows = await this.sql`DELETE FROM registry_sessions WHERE account = ${account} AND public_key = ${publicKey} RETURNING id`;
    return rows.length === 1;
  }

  /** The shared connection/pool is closed by the process that created it. */
  close(): void {}
}
